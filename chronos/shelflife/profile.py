"""Column profiling. ONE pattern table drives both the Python profiler (training data, tests) and the SQL that runs inside
the database container (serving), so train and serve cannot drift. Only aggregate statistics ever leave the database.

Patterns use only POSIX-compatible syntax ([0-9], [A-Za-z], anchors) so Python `re` and Postgres `~` agree.
"""
import json
import re
import subprocess
import os
import shlex

PATTERNS = {
    "icd10": r"^[A-TV-Z][0-9][0-9AB]([.][0-9A-Z]{1,4})?$",
    "loinc": r"^[0-9]{1,5}-[0-9]$",
    "hgvs": r"^(N[MCGP]_[0-9.]+:)?[cgpm][.][0-9_*+-]+[A-Za-z>]",
    "dob_like": r"^(19[2-9][0-9]|200[0-9]|201[0-5])-[0-9]{2}-[0-9]{2}$",
    "recent_date": r"^20(1[6-9]|2[0-9])-[0-9]{2}-[0-9]{2}",
    "phone": r"^[+]?[0-9][0-9 ()-]{8,16}$",
    "email": r"^[^@ ]+@[^@ ]+[.][A-Za-z]{2,}$",
    "national_id": r"^([0-9]{3}-[0-9]{2}-[0-9]{4}|[0-9]{12}|[A-Z]{5}[0-9]{4}[A-Z])$",
    "six_digit": r"^[0-9]{6}$",
    "token": r"^(eyJ[A-Za-z0-9_-]+[.][A-Za-z0-9_-]+[.][A-Za-z0-9_-]*|[A-Fa-f0-9]{32,}|[A-Za-z0-9_-]{40,})$",
    "currency": r"^[0-9]+[.][0-9]{2}$",
    "has_space": r"[ ]",
    "alpha_only": r"^[A-Za-z .'-]+$",
    "numeric": r"^-?[0-9]+([.][0-9]+)?$",
}
STAT_NAMES = [*PATTERNS, "mean_len", "uniqueness", "null_ratio"]
_COMPILED = {k: re.compile(v) for k, v in PATTERNS.items()}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,62}$")
SAMPLE = 200


def profile_values(values: list) -> dict:
    """Aggregate statistics over a sample of cell values (None = SQL NULL). Mirrors profile_sql()."""
    n = len(values)
    nn = [str(v) for v in values if v is not None]
    out = {k: (sum(1 for v in nn if rx.search(v)) / len(nn) if nn else 0.0) for k, rx in _COMPILED.items()}
    out["mean_len"] = sum(len(v) for v in nn) / len(nn) if nn else 0.0
    out["uniqueness"] = len(set(nn)) / len(nn) if nn else 0.0
    out["null_ratio"] = (n - len(nn)) / n if n else 0.0
    return out


def _ident(name: str) -> str:
    if not IDENT.match(name):
        raise ValueError(f"unsafe identifier {name!r}")
    return f'"{name}"'


def profile_sql(table: str, column: str) -> str:
    """One query returning one JSON row of aggregates. Runs inside the database container; no cell value is selected."""
    t, c = _ident(table), _ident(column)
    hits = ",\n    ".join(
        f"coalesce(avg(CASE WHEN v ~ '{p.replace(chr(39), chr(39) * 2)}' THEN 1.0 ELSE 0.0 END) FILTER (WHERE v IS NOT NULL), 0) AS {k}"
        for k, p in PATTERNS.items())
    return f"""WITH s AS (SELECT {c}::text AS v FROM {t} ORDER BY random() LIMIT {SAMPLE})
SELECT row_to_json(r) FROM (SELECT
    {hits},
    coalesce(avg(length(v)), 0) AS mean_len,
    coalesce(count(DISTINCT v)::float / nullif(count(v), 0), 0) AS uniqueness,
    coalesce(count(*) FILTER (WHERE v IS NULL)::float / nullif(count(*), 0), 0) AS null_ratio
  FROM s) r;"""


CONTEXT_SQL = """SELECT row_to_json(r) FROM (SELECT
  (SELECT json_agg(json_build_object('name', column_name, 'type', data_type) ORDER BY ordinal_position)
     FROM information_schema.columns WHERE table_schema = 'public' AND table_name = {t}) AS columns,
  (SELECT reltuples::bigint FROM pg_class WHERE oid = ('public.' || {t})::regclass) AS row_count,
  (SELECT coalesce(json_agg(ccu.table_name), '[]'::json) FROM information_schema.table_constraints tc
     JOIN information_schema.constraint_column_usage ccu USING (constraint_name, constraint_schema)
     WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_name = {t}) AS fk_tables) r;"""


def context_sql(table: str) -> str:
    _ident(table)
    return CONTEXT_SQL.format(t="'" + table + "'")


def psql_runner(sql: str) -> str:
    """Run SQL in the records-db container. CHRONOS_PSQL_CMD, e.g. 'docker exec -i records-db psql -U chronos -d staster -At'."""
    cmd = shlex.split(os.environ.get("CHRONOS_PSQL_CMD", "docker exec -i records-db psql -U chronos -d staster -At"))
    r = subprocess.run(cmd, input=sql, capture_output=True, text=True, timeout=60, check=True)
    return r.stdout.strip()


def profile_column(table: str, column: str, run=psql_runner) -> dict:
    return json.loads(run(profile_sql(table, column)))


def write_sql_file(path="chronos/shelflife/profile_column.sql") -> None:
    """Generated reference copy of the query (spec lists sql/profile_column.sql); the .py above is the source of truth."""
    open(path, "w").write("-- GENERATED by chronos.shelflife.profile.write_sql_file; edit PATTERNS in profile.py, not this file.\n"
                          "-- Template: replace \"TABLE\" and \"COLUMN\".\n" + profile_sql("TABLE", "COLUMN") + "\n")
